• বাংলা অনুবাদ:
হযরত আবু হুরায়রা (রা:) থেকে বর্ণিত, রাসূলুল্লাহ (সা:) বলেন: "প্রতি সোমবার ও বৃহস্পতিবার বান্দার আমলসমূহ মহান আল্লাহর দরবারে পেশ করা হয়। তাই আমি পছন্দ করি যে, সিয়াম বা রোজা অবস্থায় যেন আমার আমল পেশ করা হয়।"

• কিতাবের নাম, লেখক ও নম্বর:
