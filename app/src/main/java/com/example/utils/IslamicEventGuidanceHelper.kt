- লেখক: ইমাম মুসলিম ইবনুল হাজ্জাজ নিশাপুরী (রহ:)
- অধ্যায়: কিতাবুস সিয়াম (সুন্নাত সিয়ামের ফজিলত অনুচ্ছেদ)
- হাদিস নম্বর: ১১৬২ (ইসলামিক ফাউন্ডেশন: ২৬৪৪, পৃষ্ঠা: ৪৫২)
- মান: সহীহ (সর্বসম্মতভাবে গ্রহণযোগ্য)।

